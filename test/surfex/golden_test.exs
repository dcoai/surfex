defmodule Surfex.GoldenTest do
  @moduledoc """
  The renderer's two load-bearing claims, and its notation.

  **Order-invariance** is the property every drift gate rests on: a scanner that returned
  rows in a different order on a different run would fail the gate with no change to the
  code, and a gate that fails for no reason is a gate somebody switches off.

  **No dates** is the same failure by another route — a golden carrying a timestamp drifts
  against itself on a quiet day. It is asserted here rather than remembered, because it is
  the rule most likely to be re-broken by someone adding a helpful "generated at".
  """

  use ExUnit.Case, async: true
  @moduletag verifies: "golden-renders"

  alias Surfex.Golden
  alias Surfex.Golden.Span

  defp spec(overrides \\ %{}) do
    Map.merge(
      %{
        name: "EXAMPLE_SURFACE.md",
        purpose: "Every widget the code declares, and what verifies it.",
        task: "example.surface",
        gate: "example-surface-drift",
        hardness: :hard,
        columns: ["Item", "Evidence", "Locus"],
        rows: [
          %{
            "Item" => {:code, "alpha"},
            "Evidence" => {:atom, :unit_test},
            "Locus" => {:locus, "lib/a.ex", nil}
          },
          %{"Item" => {:code, "beta"}, "Evidence" => :absent, "Locus" => {:locus, "lib/b.ex", 12}}
        ]
      },
      overrides
    )
  end

  describe "the header block" do
    @describetag verifies: "golden-stats"

    @tag verifies: ["golden-stats", "golden-renders"]
    test "is title, purpose, attribution — in that order, contiguous" do
      [title, purpose, attribution | _] = Golden.render(spec()) |> String.split("\n")

      assert title == "# EXAMPLE_SURFACE.md"
      assert purpose == "Every widget the code declares, and what verifies it."
      assert attribution =~ "Generated by `mix example.surface --write`"
      assert attribution =~ "gate `example-surface-drift`"
      assert attribution =~ "(HARD)"
      assert attribution =~ "do not edit; a drift FAILS the gate"
    end

    @tag verifies: ["golden-shape", "golden-renders"]
    test "free prose follows the block" do
      rendered = Golden.render(spec(%{prose: "What the classes mean."}))
      [_title, _purpose, _attribution | rest] = String.split(rendered, "\n")
      assert Enum.join(rest, "\n") =~ "What the classes mean."
    end

    test "says ADVISORY when the gate is advisory, so the document states its own force" do
      rendered = Golden.render(spec(%{hardness: :advisory}))

      assert rendered =~ "(ADVISORY)"
      refute rendered =~ "(HARD)"
    end
  end

  describe "determinism" do
    @describetag verifies: "golden-order"

    test "natural_key/1 orders numbers by value within text" do
      assert Enum.sort_by(["item10", "item2", "item1"], &Surfex.Golden.natural_key/1) ==
               ["item1", "item2", "item10"]
    end

    # The property the drift gates rest on. Two scanners that agree on content but not on
    # order must produce identical bytes.
    test "row order does not change the bytes" do
      forward = spec()
      reversed = %{forward | rows: Enum.reverse(forward.rows)}

      assert Golden.render(reversed) == Golden.render(forward)
    end

    test "nor does the order of a row map's keys" do
      forward = spec()

      shuffled = %{
        forward
        | rows: Enum.map(forward.rows, &Map.new(Enum.shuffle(Map.to_list(&1))))
      }

      assert Golden.render(shuffled) == Golden.render(forward)
    end

    test "rows come out in natural-key order by default, or in the spec's :sort order" do
      rows =
        for id <- ["item10", "item2", "item1"],
            do: %{"Item" => {:code, id}, "Evidence" => :absent, "Locus" => :absent}

      order = fn rendered ->
        Regex.scan(~r/`(item\d+)`/, rendered, capture: :all_but_first) |> List.flatten()
      end

      assert order.(Golden.render(spec(%{rows: rows}))) == ["item1", "item2", "item10"]

      by_length_desc = fn %{"Item" => {:code, id}} -> -String.length(id) end
      assert order.(Golden.render(spec(%{rows: rows, sort: by_length_desc}))) |> hd() == "item10"
    end

    @tag verifies: ["golden-order", "golden-renders"]
    test "and rendering twice is rendering once" do
      assert Golden.render(spec()) == Golden.render(spec())
    end
  end

  describe "what may never appear" do
    @describetag verifies: "golden-order"

    # A golden is a stable function of source. Anything that varies independently of source
    # makes it drift against itself, and a gate that cries wolf gets disabled.
    test "no date, time or duration reaches the output" do
      rendered = Golden.render(spec())

      refute rendered =~ ~r/\d{4}-\d{2}-\d{2}/
      refute rendered =~ ~r/\d{2}:\d{2}:\d{2}/
      refute rendered =~ "generated at"
      refute rendered =~ ~r/\bms\b/
    end

    test "and no commit, branch or other VCS data" do
      rendered = Golden.render(spec())

      refute rendered =~ ~r/\b[0-9a-f]{40}\b/
      refute rendered =~ "commit"
      refute rendered =~ "branch"
    end
  end

  describe "cell notation" do
    @describetag verifies: "golden-cells"

    @tag verifies: ["golden-cells", "golden-renders"]
    test "each type renders to its documented form" do
      rendered =
        Golden.render(
          spec(%{
            columns: ["Item", "Cell"],
            rows: [
              %{"Item" => {:code, "a"}, "Cell" => {:code, "backticked"}},
              %{"Item" => {:code, "b"}, "Cell" => {:atom, :an_atom}},
              %{"Item" => {:code, "c"}, "Cell" => {:locus, "lib/x.ex", 7}},
              %{"Item" => {:code, "d"}, "Cell" => {:locus, "lib/y.ex", nil}},
              %{"Item" => {:code, "e"}, "Cell" => {:version, "a1b2c3d4"}},
              %{"Item" => {:code, "f"}, "Cell" => {:raw, "verbatim ·"}},
              %{"Item" => {:code, "g"}, "Cell" => :absent},
              %{"Item" => {:code, "h"}, "Cell" => nil},
              %{"Item" => {:code, "i"}, "Cell" => "plain"}
            ]
          })
        )

      assert rendered =~ "`backticked`"
      assert rendered =~ "`:an_atom`"
      assert rendered =~ "`lib/x.ex:7`"
      assert rendered =~ "`lib/y.ex`"
      assert rendered =~ "`a1b2c3d4`"

      assert Golden.render(
               spec(%{
                 columns: ["Item", "Cell"],
                 rows: [%{"Item" => {:code, "j"}, "Cell" => {:version, nil}}]
               })
             ) =~ "| `j` | — |"

      assert rendered =~ "verbatim ·"
      assert rendered =~ "plain"
    end

    test "an absent value and a nil both render as the em-dash glyph" do
      rendered =
        Golden.render(
          spec(%{
            columns: ["Item", "Cell"],
            rows: [
              %{"Item" => {:code, "g"}, "Cell" => :absent},
              %{"Item" => {:code, "h"}, "Cell" => nil}
            ]
          })
        )

      [_header, g, h] =
        rendered |> String.split("\n") |> Enum.filter(&String.contains?(&1, "|")) |> Enum.take(-3)

      assert g =~ "—"
      assert h =~ "—"
    end

    test "a nil-file locus is absent rather than a path of nothing" do
      rendered =
        Golden.render(
          spec(%{
            columns: ["Item", "Locus"],
            rows: [%{"Item" => {:code, "a"}, "Locus" => {:locus, nil, nil}}]
          })
        )

      assert rendered =~ "—"
    end
  end

  # #199: a cell is read back the way GitLab reads it. GFM splits the row on every `|` not
  # preceded by a backslash and turns `\|` into `|`; then a code span opens with a run of N
  # backticks and closes at the next run of exactly N, and one space is stripped from each
  # side of content that begins and ends with a space and is not all spaces.
  defp gfm_row_cells(line) do
    line
    |> String.trim()
    |> String.trim_leading("|")
    |> String.trim_trailing("|")
    |> then(&Regex.split(~r/(?<!\\)\|/, &1))
    |> Enum.map(&(&1 |> String.trim() |> String.replace("\\|", "|")))
  end

  defp gfm_code_span(cell) do
    [opener] = Regex.run(~r/\A`+/, cell)
    n = byte_size(opener)
    rest = binary_part(cell, n, byte_size(cell) - n)

    # the first backtick run of exactly n closes the span; it must end the cell
    {start, ^n} =
      ~r/`+/
      |> Regex.scan(rest, return: :index)
      |> Enum.map(&hd/1)
      |> Enum.find(fn {_at, len} -> len == n end)

    assert start + n == byte_size(rest), "the span closes before the cell ends: #{cell}"
    inner = binary_part(rest, 0, start)

    if String.starts_with?(inner, " ") and String.ends_with?(inner, " ") and
         String.trim(inner, " ") != "",
       do: binary_part(inner, 1, byte_size(inner) - 2),
       else: inner
  end

  # The one row of a golden whose Item is `cell`, read back as [item_text, other_text].
  defp gfm_read_back(cell) do
    line =
      spec(%{columns: ["Item", "Other"], rows: [%{"Item" => cell, "Other" => "x"}]})
      |> Golden.render()
      |> String.split("\n", trim: true)
      |> List.last()

    assert [item, "x"] = gfm_row_cells(line), "the row splits into other than 2 cells: #{line}"
    gfm_code_span(item)
  end

  describe "code spans read back under GFM" do
    @describetag verifies: "golden-code-spans"

    @tag verifies: ["golden-code-spans", "golden-cells"]
    test "the proposal's cases, a pipe and backtick runs of 1 to 3 at start, end and middle" do
      cases =
        ["ESC |", "|", "a|b|c", "CSI `` `", "\\|", "x\\", " a ", " ", "  ", " a", "a "] ++
          for run <- ["`", "``", "```"],
              form <- [run, run <> "a", "a" <> run, "a" <> run <> "b", run <> "a" <> run],
              do: form

      for text <- cases, do: assert(gfm_read_back({:code, text}) == text, inspect(text))

      assert IO.iodata_to_binary(Span.code("ESC |")) == "`ESC \\|`"
      assert IO.iodata_to_binary(Span.code("CSI ` x")) == "``CSI ` x``"
      assert IO.iodata_to_binary(Span.code("`")) == "`` ` ``"
      assert IO.iodata_to_binary(Span.code("plain")) == "`plain`"
    end

    test "every string up to five characters of a, space, backtick, pipe and backslash" do
      alphabet = ["a", " ", "`", "|", "\\"]

      texts =
        Enum.flat_map(1..5, fn len ->
          Enum.reduce(1..len, [""], fn _, acc -> for t <- acc, c <- alphabet, do: t <> c end)
        end)

      assert length(texts) == 3905

      for text <- texts, do: assert(gfm_read_back({:code, text}) == text, inspect(text))
    end

    test "atoms, loci and versions are spans by the same rule" do
      assert gfm_read_back({:atom, :"a|`b"}) == inspect(:"a|`b")
      assert gfm_read_back({:locus, "lib/a|b`.ex", 7}) == "lib/a|b`.ex:7"
      assert gfm_read_back({:locus, "``lib.ex", nil}) == "``lib.ex"
      assert gfm_read_back({:version, "`|`"}) == "`|`"
    end

    test "free text in a composite cell keeps a pipe as content and the rest to render" do
      assert IO.iodata_to_binary(Span.text("a | `b`")) == "a \\| `b`"

      [line] =
        spec(%{
          columns: ["Item", "Note"],
          rows: [%{"Item" => {:code, "i"}, "Note" => {:raw, Span.text("x | y")}}]
        })
        |> Golden.render()
        |> String.split("\n", trim: true)
        |> Enum.take(-1)

      assert gfm_row_cells(line) == ["`i`", "x | y"]
    end
  end

  describe "stats" do
    @describetag verifies: "golden-stats"

    test "stat/2 keeps the counts as data and renders the same line" do
      stat = Golden.stat("2 items", [{"verified", 1}, {"nothing", 1}])

      assert stat.lead == "2 items"
      assert stat.dims == [{"verified", 1}, {"nothing", 1}]

      assert IO.iodata_to_binary(stat.text) ==
               IO.iodata_to_binary(Golden.stat_line(stat.lead, stat.dims))
    end

    test "the rendered line has the documented grammar" do
      line =
        "2 items" |> Golden.stat_line([{"verified", 1}, {"nothing", 1}]) |> IO.iodata_to_binary()

      assert line == "**2 items** · verified 1 · nothing 1"
    end

    test "a bare label is a flag, with no value after it" do
      line = "3 things" |> Golden.stat_line([{"ok", 2}, "clean"]) |> IO.iodata_to_binary()

      assert line == "**3 things** · ok 2 · clean"
    end

    @tag verifies: ["golden-stats", "golden-renders"]
    test "and stats reach the output" do
      rendered = Golden.render(spec(%{stats: [Golden.stat("2 items", [{"verified", 1}])]}))

      assert rendered =~ "**2 items** · verified 1"
    end
  end

  describe "grouping" do
    test "groups render under their own headings, each with its own table" do
      rendered =
        Golden.render(
          spec(%{
            rows: nil,
            groups: [
              %{
                heading: "First",
                rows: [%{"Item" => {:code, "a"}, "Evidence" => :absent, "Locus" => :absent}]
              },
              %{
                heading: "Second",
                rows: [%{"Item" => {:code, "b"}, "Evidence" => :absent, "Locus" => :absent}]
              }
            ]
          })
        )

      assert rendered =~ "## First"
      assert rendered =~ "## Second"
      assert String.split(rendered, "| Item |") |> length() == 3
    end

    @tag verifies: ["golden-shape", "golden-renders"]
    test "a group may have its own columns" do
      rendered =
        Golden.render(
          spec(%{
            rows: nil,
            groups: [
              %{heading: "Own", columns: ["Name"], rows: [%{"Name" => {:code, "n"}}]},
              %{
                heading: "Shared",
                rows: [%{"Item" => {:code, "b"}, "Evidence" => :absent, "Locus" => :absent}]
              }
            ]
          })
        )

      assert rendered =~ "## Own\n\n| Name |"
      assert rendered =~ "| Item | Evidence | Locus |"
    end
  end
end
